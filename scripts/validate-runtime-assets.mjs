import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { brotliCompressSync, constants as zlibConstants, gzipSync } from 'node:zlib';
import yaml from 'js-yaml';
import {
  hashBytes,
  inspectGlbJson,
  readGlbJson,
} from './lib/glb-inspection.mjs';
import { GLTFPACK_VERSION } from './lib/gltfpack-tool.mjs';
import {
  officialGltfWarningBaseline,
  validateGlbWithOfficialValidator,
} from './lib/official-gltf-validation.mjs';
import {
  configuredRuntimeScenes,
  runtimeAssetTextureTiers,
} from './lib/runtime-asset-sources.mjs';
import {
  RUNTIME_ASSET_PROFILES,
  RUNTIME_ASSET_PROFILE_VERSION,
  runtimeAssetProfile,
  selectRuntimeAssetProfile,
} from './runtime-asset-profiles.mjs';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = path.join(repositoryRoot, 'assets', 'runtime-asset-manifest.json');
const PIPELINE_CACHE_VERSION = 2;

function verifyFile(relativePath, expectedHash, expectedBytes) {
  const filePath = path.resolve(repositoryRoot, relativePath);
  if (!filePath.startsWith(`${repositoryRoot}${path.sep}`) || !fs.existsSync(filePath)) {
    throw new Error(`Missing runtime asset file ${relativePath}.`);
  }
  const bytes = fs.readFileSync(filePath);
  if (bytes.length !== expectedBytes || hashBytes(bytes) !== expectedHash) {
    throw new Error(`${relativePath} does not match the runtime asset manifest.`);
  }
  return { bytes, json: readGlbJson(bytes, relativePath) };
}

function boundsTolerance(bounds) {
  const extent = Math.max(
    ...bounds.max.map((value, axis) => Math.abs(value - bounds.min[axis])),
  );
  return Math.max(0.002, extent * 0.00005);
}

function verifySemanticGeometry(scene, sourceStats, outputStats) {
  if (!sourceStats.sceneBounds || !outputStats.sceneBounds) {
    throw new Error(`${scene} is missing world-space POSITION bounds.`);
  }
  const boundDelta = Math.max(
    ...sourceStats.sceneBounds.min.map(
      (value, axis) => Math.abs(value - outputStats.sceneBounds.min[axis]),
    ),
    ...sourceStats.sceneBounds.max.map(
      (value, axis) => Math.abs(value - outputStats.sceneBounds.max[axis]),
    ),
  );
  if (boundDelta > boundsTolerance(sourceStats.sceneBounds)) {
    throw new Error(`${scene} world-space bounds changed during optimization.`);
  }
  if (sourceStats.drawParts !== outputStats.drawParts
      || JSON.stringify(sourceStats.materialTriangleCounts)
        !== JSON.stringify(outputStats.materialTriangleCounts)) {
    throw new Error(`${scene} primitive/material assignments changed during optimization.`);
  }
  if (outputStats.logicalVertexBytes > sourceStats.logicalVertexBytes
      || outputStats.logicalIndexBytes > sourceStats.logicalIndexBytes) {
    throw new Error(`${scene} logical decoded geometry grew during optimization.`);
  }
}

function expectedCacheKey(sourceSha256, profileName, optimizerArgs) {
  return hashBytes(Buffer.from(JSON.stringify({
    pipelineCacheVersion: PIPELINE_CACHE_VERSION,
    profileVersion: RUNTIME_ASSET_PROFILE_VERSION,
    gltfpackVersion: GLTFPACK_VERSION,
    sourceSha256,
    profileName,
    optimizerArgs,
  })));
}

function transferCompression(bytes) {
  return {
    gzipBytes: gzipSync(bytes, { level: 9 }).length,
    brotliBytes: brotliCompressSync(bytes, {
      params: {
        [zlibConstants.BROTLI_PARAM_QUALITY]: 9,
      },
    }).length,
  };
}

if (!fs.existsSync(manifestPath)) {
  throw new Error('Missing runtime asset manifest; run npm run optimize:runtime-assets.');
}

const editorConfig = yaml.load(
  fs.readFileSync(path.join(repositoryRoot, 'editor.config.yaml'), 'utf8'),
);
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
if (manifest.version !== 2
    || manifest.optimizer?.name !== 'gltfpack'
    || manifest.optimizer?.version !== GLTFPACK_VERSION) {
  throw new Error(`Runtime assets must be generated by gltfpack ${GLTFPACK_VERSION}.`);
}
if (manifest.optimizer.profileVersion !== RUNTIME_ASSET_PROFILE_VERSION) {
  throw new Error('Runtime asset texture-profile version is stale.');
}
for (const [name, profile] of Object.entries(RUNTIME_ASSET_PROFILES)) {
  const recorded = manifest.optimizer.profiles?.[name];
  if (recorded?.description !== profile.description
      || JSON.stringify(recorded?.args) !== JSON.stringify(profile.args)) {
    throw new Error(`Runtime optimizer profile "${name}" does not match source config.`);
  }
}
const textureTiers = runtimeAssetTextureTiers(editorConfig);
const expectedScenes = configuredRuntimeScenes(editorConfig);
const actualScenes = manifest.assets?.map((asset) => asset.scene) ?? [];
if (JSON.stringify(actualScenes) !== JSON.stringify(expectedScenes)) {
  throw new Error('Runtime asset manifest does not match configured GLBs in order.');
}

let sourceBytesTotal = 0;
let outputBytesTotal = 0;
let gzipBytesTotal = 0;
let brotliBytesTotal = 0;
let logicalSourceVertexBytesTotal = 0;
let logicalOutputVertexBytesTotal = 0;
let logicalSourceIndexBytesTotal = 0;
let logicalOutputIndexBytesTotal = 0;
for (const asset of manifest.assets) {
  const source = verifyFile(asset.source, asset.sourceSha256, asset.sourceBytes);
  const output = verifyFile(asset.output, asset.outputSha256, asset.outputBytes);
  const sourceStats = inspectGlbJson(source.json);
  const outputStats = inspectGlbJson(output.json);
  if (JSON.stringify(sourceStats) !== JSON.stringify(asset.sourceStats)
      || JSON.stringify(outputStats) !== JSON.stringify(asset.outputStats)) {
    throw new Error(`${asset.scene} GLB structure does not match the runtime manifest.`);
  }
  if (sourceStats.renderedTriangles !== outputStats.renderedTriangles) {
    throw new Error(`${asset.scene} rendered triangle count changed during optimization.`);
  }
  verifySemanticGeometry(asset.scene, sourceStats, outputStats);
  const expectedProfile = selectRuntimeAssetProfile(
    source.json,
    textureTiers.get(asset.scene) ?? 'hero',
  );
  const profile = runtimeAssetProfile(expectedProfile);
  if (asset.profile !== expectedProfile
      || JSON.stringify(asset.optimizerArgs) !== JSON.stringify(profile.args)) {
    throw new Error(`${asset.scene} uses the wrong runtime asset profile.`);
  }
  for (const requiredArg of ['-cc', '-kn', '-km', '-ke', '-vpf', '-tc', '-tu']) {
    if (!asset.optimizerArgs.includes(requiredArg)) {
      throw new Error(`${asset.scene} is missing optimizer option ${requiredArg}.`);
    }
  }
  if (asset.optimizerArgs.includes('-si')) {
    throw new Error(`${asset.scene} must not simplify authored L0 geometry.`);
  }
  if (asset.cacheKey !== expectedCacheKey(
    asset.sourceSha256,
    asset.profile,
    asset.optimizerArgs,
  )) {
    throw new Error(`${asset.scene} has an invalid optimizer cache key.`);
  }
  for (const name of sourceStats.nodeNames) {
    if (!outputStats.nodeNames.includes(name)) {
      throw new Error(`${asset.scene} is missing named node "${name}".`);
    }
  }
  for (const name of sourceStats.materialNames) {
    if (!outputStats.materialNames.includes(name)) {
      throw new Error(`${asset.scene} is missing named material "${name}".`);
    }
  }
  if (sourceStats.skins !== outputStats.skins
      || JSON.stringify(sourceStats.animationNames) !== JSON.stringify(outputStats.animationNames)) {
    throw new Error(`${asset.scene} animation or skin contracts changed during optimization.`);
  }
  if (JSON.stringify(source.json.asset?.extras ?? null)
      !== JSON.stringify(output.json.asset?.extras ?? null)) {
    throw new Error(`${asset.scene} asset provenance changed during optimization.`);
  }
  if (sourceStats.renderedTriangles > 0
      && !outputStats.extensionsRequired.includes('EXT_meshopt_compression')) {
    throw new Error(`${asset.scene} is missing required meshopt compression.`);
  }
  if (sourceStats.textures > 0
      && !outputStats.extensionsRequired.includes('KHR_texture_basisu')) {
    throw new Error(`${asset.scene} is missing required KTX2 texture compression.`);
  }
  if ((output.json.images ?? []).some((image) => image.mimeType !== 'image/ktx2')) {
    throw new Error(`${asset.scene} contains a non-KTX2 embedded runtime image.`);
  }
  const inheritedWarnings = await officialGltfWarningBaseline(
    source.bytes,
    asset.source,
  );
  const officialValidation = await validateGlbWithOfficialValidator(
    output.bytes,
    asset.output,
    { inheritedWarnings },
  );
  if (JSON.stringify(officialValidation) !== JSON.stringify(asset.officialValidation)) {
    throw new Error(`${asset.scene} official glTF validation summary is stale.`);
  }
  const compressed = transferCompression(output.bytes);
  if (compressed.gzipBytes !== asset.gzipBytes
      || compressed.brotliBytes !== asset.brotliBytes) {
    throw new Error(`${asset.scene} transfer-compression metrics are stale.`);
  }
  sourceBytesTotal += source.bytes.length;
  outputBytesTotal += output.bytes.length;
  gzipBytesTotal += compressed.gzipBytes;
  brotliBytesTotal += compressed.brotliBytes;
  logicalSourceVertexBytesTotal += sourceStats.logicalVertexBytes;
  logicalOutputVertexBytesTotal += outputStats.logicalVertexBytes;
  logicalSourceIndexBytesTotal += sourceStats.logicalIndexBytes;
  logicalOutputIndexBytesTotal += outputStats.logicalIndexBytes;
}

const savedBytes = sourceBytesTotal - outputBytesTotal;
const reductionRatio = Number((savedBytes / sourceBytesTotal).toFixed(6));
if (sourceBytesTotal !== manifest.totals?.sourceBytes
    || outputBytesTotal !== manifest.totals?.outputBytes
    || gzipBytesTotal !== manifest.totals?.gzipBytes
    || brotliBytesTotal !== manifest.totals?.brotliBytes
    || logicalSourceVertexBytesTotal !== manifest.totals?.logicalSourceVertexBytes
    || logicalOutputVertexBytesTotal !== manifest.totals?.logicalOutputVertexBytes
    || logicalSourceIndexBytesTotal !== manifest.totals?.logicalSourceIndexBytes
    || logicalOutputIndexBytesTotal !== manifest.totals?.logicalOutputIndexBytes
    || savedBytes !== manifest.totals?.savedBytes
    || reductionRatio !== manifest.totals?.reductionRatio
    || outputBytesTotal >= sourceBytesTotal) {
  throw new Error('Runtime asset size totals are invalid.');
}

console.log(
  `validated ${manifest.assets.length} meshopt/KTX2 GLBs: `
  + `${(sourceBytesTotal / 1024 / 1024).toFixed(2)} -> `
  + `${(outputBytesTotal / 1024 / 1024).toFixed(2)} MiB raw, `
  + `${(brotliBytesTotal / 1024 / 1024).toFixed(2)} MiB Brotli`,
);
