import fs from 'node:fs';
import yaml from 'js-yaml';

const root = new URL('../src/editor/workshop/shapes/config/', import.meta.url);
const load = (name) => yaml.load(fs.readFileSync(new URL(name, root), 'utf8'));
const source = load('castle.yml');
if (source.version !== 1) throw new Error('Unsupported castle config version.');
const positive = (group, limits) => {
  for (const [field, [min, max]] of Object.entries(limits)) {
    const value = source[group]?.[field];
    if (!Number.isFinite(value) || value < min || value > max) throw new Error(`Invalid ${group}.${field}`);
  }
};
positive('crown', { projection: [0.1, 1.5], height: [0.2, 3], parapetThickness: [0.15, 0.8], corbelSpacing: [0.3, 3],
  corbelWidth: [0.1, 1], corbelDrop: [0.3, 2.5], corbelSteps: [1, 6], arcadeLintel: [0.05, 0.5], arcadeDepth: [0.08, 0.6],
  merlonWidth: [0.3, 3], merlonGap: [0.2, 3], merlonHeight: [0.3, 2.5], copingHeight: [0.03, 0.3], copingOverhang: [0, 0.15] });
positive('turret', { width: [1, 6], height: [1.5, 16], projection: [0.2, 1], thickness: [0.12, 0.5], roofRise: [0.3, 4],
  roofOverhang: [0.05, 0.6], corbelSteps: [2, 8], corbelDrop: [0.2, 2] });
positive('masonry', { ashlarCourse: [0.15, 0.8], ashlarLength: [0.25, 1.6] });
const presets = fs.existsSync(new URL('castle-presets.yml', root)) ? load('castle-presets.yml') : { presets: [] };
if (!Array.isArray(presets.presets)) throw new Error('castle-presets.yml requires a presets list.');
for (const preset of presets.presets) {
  if (!/^[a-z][a-z0-9-]*$/.test(preset.id ?? '') || typeof preset.label !== 'string' || !Array.isArray(preset.primitives) || !preset.primitives.length)
    throw new Error(`Invalid castle preset: ${preset.id}`);
}
const { version, ...config } = source; void version;
const output = '// Generated by tools/generate-workshop-castle.mjs; edit config/castle.yml and config/castle-presets.yml.\n'
  + `export const SHAPE_CASTLE_CONFIG = Object.freeze(${JSON.stringify(config, null, 2)});\n`
  + `export const SHAPE_CASTLE_PRESETS = Object.freeze(${JSON.stringify(presets.presets, null, 2)});\n`;
const target = new URL('ShapeCastleConfig.generated.js', root);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Castle config is stale.');
} else fs.writeFileSync(target, output);
